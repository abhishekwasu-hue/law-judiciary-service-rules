"""app_seed_gr.py — build supabase/seed.sql (gr_library rows) from pdf/gr/INDEX.tsv. Re-run after INDEX.tsv changes.
Usage: python tools/app_seed_gr.py [pdf/gr/INDEX.tsv] [supabase/seed.sql]"""
import csv
import re
import sys


def q(v):
    return "null" if v in (None, "") else "'" + v.replace("'", "''") + "'"


def main(src="pdf/gr/INDEX.tsv", out="supabase/seed.sql"):
    rows = {}
    with open(src, encoding="utf-8") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            code = (r.get("code") or "").strip()
            if not code or code in rows:
                continue
            date = (r.get("date") or "").strip()
            if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
                m = re.match(r"(\d{4})(\d{2})(\d{2})", code)  # GR codes start with yyyymmdd
                date = f"{m[1]}-{m[2]}-{m[3]}" if m else ""
            title = (r.get("title") or "").strip()
            if title and not re.search(r"[ऀ-ॿA-Za-z]{3}", title):
                title = ""  # legacy-font garbage in INDEX.tsv
            url = "" if code.startswith("SC_") else f"https://gr.maharashtra.gov.in/Site/Upload/Government%20Resolutions/Marathi/{code}.pdf"
            rows[code] = (code, date, (r.get("department") or "").strip(), title, f"gr-library/{code}.pdf", url)
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- generated by tools/app_seed_gr.py from pdf/gr/INDEX.tsv\n")
        for c, d, dep, t, sp, u in rows.values():
            f.write(f"insert into gr_library (code, date, department, title, storage_path, source_url) values "
                    f"({q(c)}, {q(d)}, {q(dep)}, {q(t)}, {q(sp)}, {q(u)}) on conflict (code) do nothing;\n")
    print(f"{len(rows)} rows -> {out}")


if __name__ == "__main__":
    main(*sys.argv[1:])
